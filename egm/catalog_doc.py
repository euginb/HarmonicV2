class _Catalog(doc_yaml.Doc):
    """Каталог: шапка файла и таблица комментариев этого документа."""
    HEADER = HEADER
    GLOSSARY = GLOSSARY
    PATTERNS = PATTERNS
    GENERIC = GENERIC


class _CatalogWithAccuracy(_Catalog):
    """Таблицы точности: ключи — заголовки каталога с точками внутри, путь не разобрать
    по сегментам, поэтому листья accuracy.* получают общий комментарий."""

    def comment(self, path):
        if path.startswith("accuracy."):
            return ("Значение таблицы точности каталога: ключ — заголовок таблицы и строка, "
                    "значение — по классам точности C/H/P/SP/UP.")
        return super().comment(path)


_DOC = _CatalogWithAccuracy()


def comment(path):
    """Комментарий к пути ключа."""
    return _DOC.comment(path)


def dump(db):
    """Словарь каталога -> текст specs/catalog_hiwin_hg.yaml."""
    return _DOC.dump(db)


def load_catalog(specs_dir=None):
    """Каталог -> dict. Читает .yaml; нет — старый .json (переходный путь)."""
    d = Path(specs_dir) if specs_dir else Path(__file__).resolve().parents[1] / "specs"
    y, j = d / f"{FILE}.yaml", d / f"{FILE}.json"
    if y.exists():
        return doc_yaml.load(y) or {}
    if j.exists():
        import json
        return json.loads(j.read_text(encoding="utf-8"))
    return {}


def self_test():
    """Комментарии покрывают ключи каретки, рельса, типоразмера и точности."""
    db = {"source": "x.md", "catalog": "G99", "classes": ["C", "H"], "preloads": ["Z0"],
          "blocks": {"HGH25CA": {"type": "HGH", "size": 25, "load": "CA", "mount": "A",
                                 "dims": {"H": 40.0, "W": 48.0, "M": "M6x8"},
                                 "loads": {"C": 26.48, "MR": 0.42, "mass_block_kg": 0.51}}},
          "rails": {"HGR25R": {"size": 25, "mount": "R",
                               "dims": {"WR": 23.0, "P": 60.0, "rail_bolt": "M6x20"}}},
          "sizes": {"25": {"parallel_um": {"Z0": 25.0}, "height_um": {"Z0": 130.0},
                           "mounting": {"r1": 0.5}, "lengths": [[160.0, 3]],
                           "P": 60.0, "Es": 20.0, "max_std": 1960.0, "max_len": 2000.0}},
          "accuracy": {"Table 2-1-3": {"Variation of height H": {"C": 0.02}}},
          "unparsed": ["Содержание"], "conflicts": []}
    txt = dump(db)
    assert doc_yaml.yaml.safe_load(txt) == db, txt
    miss = []
    def scan(n, p=""):
        if isinstance(n, dict):
            for k, v in n.items():
                q = f"{p}.{k}" if p else str(k)
                if not comment(q):
                    miss.append(q)
                scan(v, q)
        elif isinstance(n, list):
            for x in n:
                scan(x, p + "[]")
    scan(db)
    assert not miss, miss
    return True
